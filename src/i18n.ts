/** Current strings; mutated in place by setLanguage so every module sees the switch. */
export const T: Dict = { ...en };

const dicts: Record<string, Dict> = {
	en,
	'en-gb': enGB,
	ru,
	de,
	fr,
	it,
	es,
	pt,
};

export function setLanguage(lang: string): void {
	const code = lang.trim().toLowerCase().replace('_', '-');
	const exact = dicts[code];
	const base = dicts[code.split('-')[0] ?? ''];
	Object.assign(T, exact ?? base ?? en);
}
